
from typing import Literal

from pydantic import BaseModel, Field

from langchain_google_genai import ChatGoogleGenerativeAI

from config.settings import (
    GOOGLE_API_KEY,
    GEMINI_MODEL
)


class QueryPlan(BaseModel):
    """
    Structured analytical instructions generated by Gemini.
    """

    operation: Literal[
        "dataset_overview",
        "column_summary",
        "aggregate",
        "top_categories",
        "correlation",
        "missing_values",
        "unsupported"
    ] = Field(
        description="The analytical operation to perform."
    )

    column: str | None = Field(
        default=None,
        description="Primary dataset column involved."
    )

    group_by: str | None = Field(
        default=None,
        description="Categorical or date column used for grouping."
    )

    aggregation: Literal[
        "sum",
        "mean",
        "count",
        "min",
        "max"
    ] = Field(
        default="sum",
        description="Aggregation method."
    )

    second_column: str | None = Field(
        default=None,
        description="Second numerical column for correlation."
    )

    explanation: str = Field(
        description="Brief explanation of the intended analysis."
    )


def get_gemini_model():
    """
    Initialize the Gemini model.
    """

    if not GOOGLE_API_KEY:
        raise ValueError(
            "Google API key is missing. "
            "Please configure GOOGLE_API_KEY in your .env file."
        )

    return ChatGoogleGenerativeAI(
        model=GEMINI_MODEL,
        google_api_key=GOOGLE_API_KEY,
    )


def create_query_plan(
    user_question: str,
    df
) -> QueryPlan:
    """
    Convert a natural-language question into a validated query plan.
    """

    model = get_gemini_model()

    structured_model = model.with_structured_output(
        QueryPlan,
        method="json_schema"
    )

    column_information = []

    for column in df.columns:

        column_information.append({
            "name": str(column),
            "dtype": str(df[column].dtype),
            "unique_values": int(df[column].nunique()),
            "missing_values": int(df[column].isna().sum())
        })

    prompt = f"""
You are an analytical query planner for an AI Data Analysis platform.

Your job is to understand the user's question and select
the correct analytical operation.

AVAILABLE OPERATIONS:

1. dataset_overview:
   General questions about dataset size, structure and columns.

2. column_summary:
   Questions about an individual column, including its
   average, median, minimum, maximum or distribution.

3. aggregate:
   Questions involving sum, average, count, minimum or maximum.
   Use group_by when comparing categories or groups.

4. top_categories:
   Questions asking for the most frequent categories or
   highest-count category.

5. correlation:
   Questions about relationships between two numerical columns.

6. missing_values:
   Questions about missing or null values.

7. unsupported:
   Questions that cannot be answered using the available operations.

DATASET COLUMN INFORMATION:

{column_information}

USER QUESTION:

{user_question}

RULES:

- Use only exact column names from the dataset.
- Never invent column names.
- Do not generate Python code or SQL.
- Do not assume that a numerical identifier is a measurement.
- Select an operation that best matches the question.
- If the requested analysis is unclear or unsupported,
  select unsupported.
- Return a structured analytical plan.
"""

    plan = structured_model.invoke(prompt)

    # Validate all referenced columns
    valid_columns = set(df.columns)

    for selected_column in [
        plan.column,
        plan.group_by,
        plan.second_column
    ]:

        if (
            selected_column is not None
            and selected_column not in valid_columns
        ):

            raise ValueError(
                f"Gemini selected an invalid column: "
                f"{selected_column}"
            )

    return plan
